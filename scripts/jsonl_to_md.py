#!/usr/bin/env python3
"""
Minimal JSONL -> Markdown converter for Claude Code sessions.

Reverse-engineered from specstory-cli (pkg/providers/claudecode/agent_session.go
and pkg/session/markdown.go). Produces output structurally compatible with
specstory's MD format. Does NOT replicate every per-tool formatter — uses a
small registry covering Bash/Read/Write/Edit/Grep + a default fallback.

Usage:
    python jsonl_to_md.py <session-id-or-jsonl-path>  [--out path.md]

If a bare session ID is passed, looks under
~/.claude/projects/-Users-dennisk-Documents-project---bib-content-gen/.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Iterable

# ---- Constants matching specstory output ----
HEADER_COMMENT = "<!-- Generated by SpecStory, Markdown v2.1.0 -->"
PROVIDER_NAME = "Claude Code"

# Strip ANSI color codes from terminal output that ends up in tool results
ANSI_RE = re.compile(r"\x1b\[[0-9;]*m")
# <system-reminder> tags are model-internal scaffolding; specstory strips them
SYSTEM_REMINDER_RE = re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL)


# ---------- I/O helpers ----------

def find_jsonl(arg: str) -> Path:
    """Accept either a full path or just a session UUID."""
    p = Path(arg)
    if p.exists():
        return p
    # Treat as session ID
    base = Path.home() / ".claude/projects/-Users-dennisk-Documents-project---bib-content-gen"
    candidate = base / f"{arg}.jsonl"
    if candidate.exists():
        return candidate
    sys.exit(f"Could not find JSONL for: {arg}")


def iter_records(path: Path) -> Iterable[dict]:
    """Yield parsed JSON objects, skipping corrupt lines."""
    with path.open("r", encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line:
                continue
            try:
                yield json.loads(line)
            except json.JSONDecodeError as e:
                print(f"  warn: line {i}: {e}", file=sys.stderr)


# ---------- Timestamp formatting ----------

def fmt_ts(iso: str | None) -> str:
    """ISO 8601 -> '2026-04-25 22:24:31Z' (UTC)."""
    if not iso:
        return ""
    try:
        # Python <3.11 doesn't accept 'Z'; normalize to +00:00
        dt = datetime.fromisoformat(iso.replace("Z", "+00:00"))
        return dt.strftime("%Y-%m-%d %H:%M:%S") + "Z"
    except ValueError:
        return iso


# ---------- Tool-specific formatters ----------
# Each takes (input_dict, description) and returns the inner markdown
# (everything inside <details> after the <summary> line).

def fmt_bash(inp: dict, desc: str) -> str:
    out = []
    if desc:
        out.append(desc)
    cmd = inp.get("command", "")
    if cmd:
        if "\n" in cmd:
            out.append(f"\n```bash\n{cmd}\n```")
        else:
            out.append(f"\n`{cmd}`")
    return "".join(out)


def fmt_write(inp: dict, desc: str) -> str:
    out = []
    if desc:
        out.append(desc)
    content = inp.get("content", "")
    file_path = inp.get("file_path", "")
    lang = _lang_from_ext(file_path)
    if content:
        # Escape triple backticks (specstory does this)
        content = content.replace("```", "\\```")
        out.append(f"\n```{lang}\n{content}\n```")
    return "".join(out)


def fmt_read(inp: dict, desc: str) -> str:
    parts = []
    if (path := inp.get("file_path")):
        parts.append(f" `{path}`")
    if desc:
        parts.append(f" {desc}")
    return "".join(parts)


def fmt_grep(inp: dict, desc: str) -> str:
    parts = []
    if (path := inp.get("path")):
        parts.append(f" path `{path}`")
    if (pattern := inp.get("pattern")):
        parts.append(f" pattern `{pattern}`")
    if (include := inp.get("include") or inp.get("glob")):
        parts.append(f" include `{include}`")
    if desc:
        parts.append(f" {desc}")
    return "".join(parts)


def fmt_default(inp: dict, desc: str) -> str:
    """Sorted key-value list, mimicking specstory's renderGenericTool."""
    out = []
    if desc:
        out.append(desc + "\n")
    if inp:
        out.append("\n**Input:**\n\n")
        for k in sorted(k for k in inp if not k.startswith("_")):
            out.append(f"- {k}: `{inp[k]}`\n")
    return "".join(out)


TOOL_FORMATTERS = {
    "Bash": fmt_bash,
    "Write": fmt_write,
    "Read": fmt_read,
    "Edit": fmt_default,
    "MultiEdit": fmt_default,
    "Grep": fmt_grep,
    "Glob": fmt_grep,
}

TOOL_TYPES = {  # for data-tool-type attribute
    "Bash": "shell", "Write": "write", "Edit": "write", "MultiEdit": "write",
    "Read": "read", "Grep": "search", "Glob": "search",
    "WebFetch": "read", "WebSearch": "search",
    "TodoWrite": "task", "Task": "generic",
}


def _lang_from_ext(path: str) -> str:
    ext = Path(path).suffix.lstrip(".").lower()
    return {"js": "javascript", "ts": "typescript", "py": "python",
            "rb": "ruby", "yml": "yaml", "md": "markdown"}.get(ext, ext)


# ---------- Cleanup helpers ----------

def clean_tool_output(text: str) -> str:
    """Strip ANSI codes and <system-reminder> tags."""
    text = SYSTEM_REMINDER_RE.sub("", text)
    text = ANSI_RE.sub("", text)
    return text.rstrip(" \t")


# ---------- Core conversion ----------

def extract_assistant_parts(record: dict) -> tuple[list[tuple[str, str]], dict | None]:
    """
    Walk an assistant record's content array, returning:
      - list of (kind, text) pairs for text/thinking
      - the tool_use dict if present (we attach output later)
    """
    msg = record.get("message", {})
    content = msg.get("content", [])
    parts: list[tuple[str, str]] = []
    tool_use: dict | None = None
    if isinstance(content, list):
        for item in content:
            if not isinstance(item, dict):
                continue
            t = item.get("type")
            if t == "text" and item.get("text"):
                parts.append(("text", item["text"]))
            elif t == "thinking" and item.get("thinking"):
                parts.append(("thinking", item["thinking"]))
            elif t == "tool_use":
                tool_use = {
                    "id": item.get("id"),
                    "name": item.get("name", ""),
                    "input": item.get("input", {}) or {},
                }
    return parts, tool_use


def extract_tool_result(record: dict) -> tuple[str, str, bool] | None:
    """If user record is a tool_result, return (tool_use_id, content_text, is_error)."""
    msg = record.get("message", {})
    content = msg.get("content")
    if not isinstance(content, list) or not content:
        return None
    first = content[0]
    if not isinstance(first, dict) or first.get("type") != "tool_result":
        return None
    raw = first.get("content", "")
    if isinstance(raw, list):
        # Sometimes it's [{"type":"text","text":"..."}]
        raw = "\n".join(c.get("text", "") for c in raw if isinstance(c, dict))
    return first.get("tool_use_id", ""), raw or "", bool(first.get("is_error"))


def extract_user_text(record: dict) -> str:
    """Get plain user text (only if not a tool_result)."""
    msg = record.get("message", {})
    content = msg.get("content", "")
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "\n".join(
            c.get("text", "") for c in content
            if isinstance(c, dict) and c.get("type") == "text"
        )
    return ""


def render_tool_block(tool: dict, output: tuple[str, bool] | None) -> str:
    """Render <tool-use><details>...</details></tool-use> block."""
    name = tool["name"]
    ttype = TOOL_TYPES.get(name, "unknown")
    inp = dict(tool.get("input", {}))
    desc = inp.pop("description", "") if isinstance(inp.get("description"), str) else ""

    formatter = TOOL_FORMATTERS.get(name, fmt_default)
    body = formatter(inp, desc)

    out = [
        f'<tool-use data-tool-type="{ttype}" data-tool-name="{name}"><details>\n',
        f"<summary>Tool use: **{name}**</summary>\n",
        body,
    ]
    if not body.endswith("\n"):
        out.append("\n")

    if output is not None:
        content, is_error = output
        cleaned = clean_tool_output(content)
        if cleaned:
            label = "Error" if is_error else None
            if label:
                out.append(f"\n**{label}:**\n")
            out.append("\n```text\n")
            out.append(cleaned)
            out.append("\n```\n")

    out.append("</details></tool-use>\n")
    return "".join(out)


def convert(jsonl_path: Path) -> str:
    """Convert one JSONL file to a markdown string."""
    md: list[str] = [HEADER_COMMENT, "", ""]

    # First pass: collect records, find session ID + first timestamp
    records = list(iter_records(jsonl_path))
    session_id = ""
    first_ts = ""
    for r in records:
        if not session_id and r.get("sessionId"):
            session_id = r["sessionId"]
        if not first_ts and r.get("type") in ("user", "assistant") and r.get("timestamp"):
            first_ts = r["timestamp"]
        if session_id and first_ts:
            break

    md.append(f"# {fmt_ts(first_ts)}")
    md.append("")
    md.append(f"<!-- {PROVIDER_NAME} Session {session_id} ({fmt_ts(first_ts)}) -->")
    md.append("")

    # Second pass: emit messages, threading tool_use -> tool_result
    pending_tools: dict[str, dict] = {}  # tool_use_id -> tool dict (waiting for result)
    rendered_tool_ids: set[str] = set()
    prev_role = ""

    # Build a quick map: tool_use_id -> (content, is_error) by scanning ahead once
    tool_results: dict[str, tuple[str, bool]] = {}
    for r in records:
        if r.get("type") != "user":
            continue
        tr = extract_tool_result(r)
        if tr:
            tool_results[tr[0]] = (tr[1], tr[2])

    def add_separator(role: str) -> None:
        nonlocal prev_role
        if prev_role and prev_role != role:
            md.append("---")
            md.append("")
        prev_role = role

    for r in records:
        rtype = r.get("type")
        ts = r.get("timestamp", "")

        if rtype == "user":
            # Skip user records that are pure tool_result (already merged below)
            if extract_tool_result(r) is not None:
                continue
            text = extract_user_text(r)
            if not text.strip():
                continue
            add_separator("user")
            md.append(f"_**User ({fmt_ts(ts)})**_")
            md.append("")
            md.append(text)
            md.append("")

        elif rtype == "assistant":
            parts, tool = extract_assistant_parts(r)
            model = r.get("message", {}).get("model", "")
            # Skip empty assistant turns (signature-only thinking with no text/tool)
            if not parts and tool is None:
                continue
            add_separator("agent")
            header = "_**Agent"
            if model and ts:
                header += f" ({model} {fmt_ts(ts)})"
            elif model:
                header += f" ({model})"
            elif ts:
                header += f" ({fmt_ts(ts)})"
            header += "**_"
            md.append(header)
            md.append("")
            for kind, text in parts:
                if kind == "text":
                    md.append(text)
                    md.append("")
                elif kind == "thinking":
                    md.append("<think><details><summary>Thought Process</summary>")
                    md.append(text)
                    md.append("</details></think>")
                    md.append("")
            if tool:
                output = tool_results.get(tool["id"])
                md.append(render_tool_block(tool, output))

        # All other types (system, attachment, custom-title, file-history-snapshot,
        # agent-name, permission-mode, etc.) are silently dropped — same as specstory.

    return "\n".join(md).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", help="Session UUID or path to .jsonl file")
    parser.add_argument("--out", type=Path, help="Output .md path (default: stdout)")
    args = parser.parse_args()

    jsonl_path = find_jsonl(args.source)
    md = convert(jsonl_path)

    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(md, encoding="utf-8")
        print(f"Wrote {len(md):,} bytes to {args.out}", file=sys.stderr)
    else:
        sys.stdout.write(md)


if __name__ == "__main__":
    main()
